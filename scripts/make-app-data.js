// Generates app-data.js for the mobile app (app.html) from the SAME verified
// source of truth the web app uses: data/schools/*.json → each doc.general.
// Mirrors scripts/build.js (SCHOOLS = docs.map(d=>d.general)), and adds:
//   verified: boolean  — true when the school has >=1 officially-verified fact
//                        (verifiedFacts.vf non-empty), matching the web app badge.
//   program: {name}    — real BS/MD (or accelerated) program name, when present.
// No numbers are invented; every field is copied straight from the JSON.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const dir = path.join(ROOT, 'data/schools');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.json') && !f.startsWith('_'));
const docs = files.map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
docs.sort((a, b) => (a.order ?? 0) - (b.order ?? 0));

// Fields the app actually reads (keeps app-data.js lean; all values verbatim from source).
const FIELDS = ['id','n','city','st','region','type','size','admit','g25','g75',
  's25','s75','tb','coa','merit','meritName','grad4','premed','research','bio',
  'social','dl','dlDate','note','links'];

const SCHOOLS = docs.map(d => {
  const g = d.general || {};
  const out = {};
  FIELDS.forEach(k => { out[k] = (k in g) ? g[k] : null; });
  // social lives at doc.social in some records, general.social in others
  if (out.social == null && d.social != null) out.social = d.social;
  const vf = (d.verifiedFacts && d.verifiedFacts.vf) || [];
  out.verified = vf.length > 0;
  if (d.program && d.program.name) out.program = { name: d.program.name };
  return out;
});

const banner = '// GENERATED by scripts/make-app-data.js from data/schools/*.json — do not hand-edit. Real verified data.';
const body = 'window.SCHOOLS = ' + JSON.stringify(SCHOOLS) + ';';
fs.writeFileSync(path.join(ROOT, 'app-data.js'), banner + '\n' + body + '\n');

// quick integrity summary
const v = SCHOOLS.filter(s => s.verified).length;
const p = SCHOOLS.filter(s => s.program).length;
console.log('Wrote app-data.js:', SCHOOLS.length, 'schools |', v, 'verified |', p, 'with program');
