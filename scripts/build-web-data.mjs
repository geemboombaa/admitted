// Build the browser-loadable school data from the SAME core loader the tests use.
// Emits web/schools.generated.mjs (ESM) — no fabrication, verified overrides + wedge fields intact.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadSchools } from '../core/data.mjs';

const dir = fileURLToPath(new URL('../data/schools', import.meta.url));
const schools = loadSchools(dir);
const out = fileURLToPath(new URL('../web/schools.generated.mjs', import.meta.url));
writeFileSync(out, '// GENERATED by scripts/build-web-data.mjs — do not hand-edit. Real verified data.\nexport const SCHOOLS = ' + JSON.stringify(schools) + ';\n');
console.log('wrote', schools.length, 'schools ->', out.replace(/.*[\\/]/, ''));
